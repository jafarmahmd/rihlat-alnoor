const QURAN_CACHE_PREFIX = 'rihlat_quran_surah_v1_';
const memoryCache = new Map<number, string[]>();

export async function fetchQuranSurahAyat(
  surahNumber: number,
  signal?: AbortSignal
): Promise<string[]> {
  if (LOCAL_QURAN_SURAHS[surahNumber]) {
    return LOCAL_QURAN_SURAHS[surahNumber];
  }

  const cachedMem = memoryCache.get(surahNumber);
  if (cachedMem) return cachedMem;

  if (typeof window !== 'undefined') {
    try {
      const cachedRaw = window.localStorage.getItem(
        `${QURAN_CACHE_PREFIX}${surahNumber}`
      );
      if (cachedRaw) {
        const parsed = JSON.parse(cachedRaw);
        if (Array.isArray(parsed) && parsed.length > 0) {
          memoryCache.set(surahNumber, parsed);
          return parsed;
        }
      }
    } catch {
      // Ignore storage errors
    }
  }

  const res = await fetch(
    `https://api.alquran.cloud/v1/surah/${surahNumber}/quran-uthmani`,
    { signal }
  );
  if (!res.ok) {
    throw new Error('Failed to load surah');
  }
  const json = (await res.json()) as {
    code?: number;
    data?: { ayahs?: { numberInSurah: number; text: string }[] };
  };

  const ayahs = json?.data?.ayahs;
  if (!Array.isArray(ayahs) || ayahs.length === 0) {
    throw new Error('Invalid surah response');
  }

  // Strip leading Bismillah from verse 1 when API includes it inside ayah 1 (except Surah 1 and 9)
  const BISMILLAH_UTHMANI = 'بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ ';
  const cleaned = ayahs.map((a, idx) => {
    if (idx === 0 && surahNumber !== 1 && surahNumber !== 9) {
      if (a.text.startsWith(BISMILLAH_UTHMANI)) {
        return a.text.slice(BISMILLAH_UTHMANI.length).trim();
      }
    }
    return a.text.trim();
  });

  memoryCache.set(surahNumber, cleaned);
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(
        `${QURAN_CACHE_PREFIX}${surahNumber}`,
        JSON.stringify(cleaned)
      );
    } catch {
      // Ignore storage quota issues
    }
  }

  return cleaned;
}

export function isSurahAvailableOffline(surahNumber: number): boolean {
  if (LOCAL_QURAN_SURAHS[surahNumber]) return true;
  if (memoryCache.has(surahNumber)) return true;
  if (typeof window !== 'undefined') {
    try {
      return Boolean(
        window.localStorage.getItem(`${QURAN_CACHE_PREFIX}${surahNumber}`)
      );
    } catch {
      return false;
    }
  }
  return false;
}

export function getCachedOfflineSurahCount(): number {
  return QURAN_SURAHS_META.filter((s) => isSurahAvailableOffline(s.number)).length;
}

export async function cacheAllQuranSurahsOffline(
  onProgress?: (cachedCount: number, total: number) => void,
  signal?: AbortSignal
): Promise<{ cached: number; failed: number }> {
  let cached = 0;
  let failed = 0;
  const total = QURAN_SURAHS_META.length;

  for (const surah of QURAN_SURAHS_META) {
    if (signal?.aborted) break;
    if (isSurahAvailableOffline(surah.number)) {
      cached++;
      onProgress?.(cached, total);
      continue;
    }
    try {
      await fetchQuranSurahAyat(surah.number, signal);
      cached++;
    } catch {
      failed++;
    }
    onProgress?.(cached, total);
  }

  return { cached, failed };
}
