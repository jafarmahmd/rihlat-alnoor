interface RawStationSeed {
  id: number;
  stageId: number;
  title: string;
  figureName: string;
  valueLabel: string;
  story: [string, string];
  wisdomQuote: string;
  question: string;
  options: [string, string, string];
  correctIndex: 1 | 2; // Always 2nd or 3rd option
  feedbackCorrect: string;
  feedbackWrong: [string, string];
  imagePath: string;
  imageAlt: string;
}

function buildStation(seed: RawStationSeed): StationData {
  const optionIds = ['a', 'b', 'c'] as const;
  let wrongCounter = 0;
  const builtOptions = seed.options.map((text, idx) => {
    const isCorrect = idx === seed.correctIndex;
    const feedback = isCorrect
      ? seed.feedbackCorrect
      : seed.feedbackWrong[wrongCounter++];
    return {
      id: optionIds[idx],
      text,
      isCorrect,
      feedback,
    };
  });

  return {
    id: seed.id,
    stageId: seed.stageId,
    title: seed.title,
    subtitle: seed.figureName,
    valueLabel: seed.valueLabel,
    figureName: seed.figureName,
    storyParagraphs: seed.story,
    wisdomQuote: seed.wisdomQuote,
    imagePath: seed.imagePath,
    imageAlt: seed.imageAlt,
    starsReward: 5,
    questions: [
      {
        id: `s${seed.id}-q1`,
        question: seed.question,
        options: builtOptions,
      },
    ],
  };
}

